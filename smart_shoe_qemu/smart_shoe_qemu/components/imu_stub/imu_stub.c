/* ─────────────────────────────────────────────────────────────────────────────
 * imu_stub.c  —  QEMU/simulation stub for the GY-86 (MPU-6050) IMU
 *
 * Replays a pre-recorded walking gait dataset at 200 Hz.
 * Activated when CONFIG_IMU_STUB=y (ESP-IDF) or CONFIG_IMU_STUB=y (Zephyr).
 *
 * Data format per sample:
 *   { ax, ay, az, gx, gy, gz }  — raw int16 ADC counts
 *   ax/ay/az: FS=±2g  → 1g = 16384 counts
 *   gx/gy/gz: FS=±250°/s → 131 counts per °/s
 *
 * One full gait cycle (~1 second at 200Hz = 200 samples):
 *   0–40   samples  : initial double stance (both feet on ground)
 *   40–80  samples  : loading response / heel strike
 *   80–120 samples  : mid-stance
 *   120–160 samples : push-off / toe-off
 *   160–200 samples : swing phase
 * ───────────────────────────────────────────────────────────────────────────*/

