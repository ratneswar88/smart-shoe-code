#define GAIT_DATASET_LEN  (sizeof(gait_data) / sizeof(gait_data[0]))
#define SAMPLE_PERIOD_MS  (1000 / IMU_SAMPLE_RATE_HZ)   /* 5ms at 200Hz */

/* ── Module state ──────────────────────────────────────────────────────────── */
static uint32_t s_sample_idx   = 0;
static uint32_t s_stride_count = 0;
static bool     s_initialized  = false;

/* ── Internal helpers ──────────────────────────────────────────────────────── */
static float raw_to_g(int16_t raw)   { return raw * IMU_ACCEL_SCALE; }
static float raw_to_dps(int16_t raw) { return raw * IMU_GYRO_SCALE;  }

/* Classify gait phase from sample index within a cycle */
static gait_phase_t classify_phase(uint32_t idx_in_cycle) {
    if (idx_in_cycle <  40) return GAIT_STANCE;
    if (idx_in_cycle <  80) return GAIT_HEEL_STRIKE;
    if (idx_in_cycle < 120) return GAIT_STANCE;
    if (idx_in_cycle < 160) return GAIT_PUSH_OFF;
    return GAIT_SWING;
}

/* ── Public API ────────────────────────────────────────────────────────────── */

int imu_init(void) {
    s_sample_idx   = 0;
    s_stride_count = 0;
    s_initialized  = true;
    printf("[IMU STUB] Initialised — replaying %u-sample walking gait dataset at %d Hz\n",
           (unsigned)GAIT_DATASET_LEN, IMU_SAMPLE_RATE_HZ);
    return 0;
}

int imu_read(imu_data_t *out) {
    if (!out) return -1;
    if (!s_initialized) imu_init();

    /* Throttle to 200Hz */
    STUB_DELAY_MS(SAMPLE_PERIOD_MS);

    uint32_t idx = s_sample_idx % GAIT_DATASET_LEN;
    const int16_t *s = gait_data[idx];

    out->ax_g   = raw_to_g(s[0]);
    out->ay_g   = raw_to_g(s[1]);
    out->az_g   = raw_to_g(s[2]);
    out->gx_dps = raw_to_dps(s[3]);
    out->gy_dps = raw_to_dps(s[4]);
    out->gz_dps = raw_to_dps(s[5]);
    out->temp_c = 25.0f;
    out->timestamp_us = STUB_TIME_US();

    /* Track strides */
    if (idx == 0 && s_sample_idx > 0) {
        s_stride_count++;
        printf("[IMU STUB] Stride %u complete\n", (unsigned)s_stride_count);
    }

    gait_phase_t phase = classify_phase(idx);
    (void)phase;   /* consumed by zupt module */

    s_sample_idx++;
    return 0;
}

int imu_read_raw(imu_raw_t *out) {
    if (!out) return -1;
    if (!s_initialized) imu_init();

    STUB_DELAY_MS(SAMPLE_PERIOD_MS);

    uint32_t idx = s_sample_idx % GAIT_DATASET_LEN;
    const int16_t *s = gait_data[idx];

    out->ax = s[0]; out->ay = s[1]; out->az = s[2];
    out->gx = s[3]; out->gy = s[4]; out->gz = s[5];
    out->temp_raw    = 0;
    out->timestamp_us = STUB_TIME_US();

    s_sample_idx++;
    return 0;
}

bool imu_is_stub(void) { return true; }
